"""Excel / Spreadsheet specialist evaluator (Service I).

This evaluator is **native to AAGE**.  The existing Excel analyzers are reused
as deterministic *evidence sources*; they never grade, publish or execute
anything:

* workbook bytes come from :attr:`ArtifactManifest.binary_files`;
* the assessment brief is turned into a requirement spec by the existing
  ``AssignmentInstructionParser`` (no DB access, no report fallback);
* ``RequirementEvaluator`` runs the workbook/formula/chart/pivot/VBA/Power
  Query/DAX/formatting analyzers and produces requirement observations;
* AAGE maps those observations onto its own rubric criteria, derives bounded
  marks and validated evidence, and computes the official score through
  :func:`src.services.aage.scoring.compute_breakdown`.

Legacy ``ExcelGradingService.grade_submission()``, Excel totals, Excel grade
letters and Excel confidence labels are deliberately never called or copied.
Formula strings, macros and queries are inspected only — Excel calculation,
macro execution and query/pivot refresh never happen.
"""

