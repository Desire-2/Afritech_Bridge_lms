_INSPECTION_LIMITATION = (
    "Workbook, formulas, macros, pivots and queries were inspected statically; "
    "Excel calculation, macro execution and query/pivot refresh were not performed."
)


class SpreadsheetEvaluator(BaseEvaluator):
    name = "spreadsheet"
    version = "2.0.0"
    kind = "analyzer"
    supported_disciplines = ("spreadsheet",)
    supported_extensions = EXCEL_EXT
    description = ("Native AAGE specialist: deterministic workbook analyzers "
                   "supply evidence for AAGE-owned rubric criteria and scoring.")

    # ------------------------------------------------------------------
    # Capability detection
    # ------------------------------------------------------------------

    def is_compatible(self, ctx: EvaluationContext) -> bool:
        if ctx.classification.discipline == "spreadsheet":
            return True
        workbook_ext = WORKBOOK_EXT
        if any(f.path.lower().endswith(workbook_ext) for f in ctx.artifact_files):
            return True
        if any(str(f.get("file_name", "")).lower().endswith(workbook_ext)
               for f in ctx.manifest.files):
            return True
        if not ctx.artifact_files and not (ctx.manifest.text_content or "").strip():
            return False
        has_code = any(
            f.path.lower().endswith((".py", ".js", ".ts", ".ipynb", ".html",
                                     ".java", ".go", ".sql"))
            for f in ctx.files)
        return (not has_code) and any(
            f.path.lower().endswith(".csv") for f in ctx.artifact_files)

    def criteria_for(self, ctx: EvaluationContext) -> List[Dict[str, Any]]:
        if ctx.classification.discipline == "spreadsheet":
            return list(ctx.criteria)
        return [c for c in ctx.criteria if self.handles(c)]

    # ------------------------------------------------------------------
    # Main evaluation
    # ------------------------------------------------------------------

    def evaluate(self, ctx: EvaluationContext,
                 criteria: Sequence[Dict[str, Any]]) -> EvaluatorOutput:
        output = EvaluatorOutput(evaluator_name=self.name,
                                 evaluator_version=self.version)
        workbooks = self._workbooks(ctx)
        if not workbooks:
            reason = "no workbook artefact was resolved"
            output.warnings.append(reason)
            output.criteria = self._unverified_criteria(criteria, reason)
            output.confidence = 0.0
            output.analysis = {
                "evaluator": self.name, "version": self.version,
                "workbook": None, "limitation": _INSPECTION_LIMITATION,
            }
            return output

        workbook = workbooks[0]
        spec = self._build_spec(ctx)
        analyses, analysis_warnings = self._run_analyzers(workbook, spec)
        output.warnings.extend(analysis_warnings)

        req_eval = self._evaluate_requirements(spec, analyses)
        req_results = [r for r in (req_eval.get("requirement_results") or [])
                       if isinstance(r, dict)]
        # Generic rubric criteria (for example "Charts & formatting" on a
        # workbook-only brief) need deterministic evidence too.  Derive that
        # evidence from the same static analyzer output rather than inventing
        # assignment requirements or falling back to a legacy Excel score.
        workbook_observations = self._workbook_feature_observations(spec, analyses)
        req_results.extend(workbook_observations)
        if not req_results:
            output.warnings.append(
                "no assessment requirements could be derived from the brief")

        validator = EvidenceValidator(
            manifest_paths=ctx.artifact_paths + ["written response"],
            has_written_response=bool(ctx.manifest.text_content),
        )

        by_key: Dict[str, CriterionEvaluation] = {}
        mapping: Dict[str, List[str]] = {}
        manual_review_keys: List[str] = []
        for crit in criteria:
            key = str(crit.get("criterion_key") or crit.get("key") or "")
            deterministic, manual = self._match_requirements(crit, req_results)
            mapping[key] = [str(r.get("requirement_id") or "") for r in deterministic + manual]
            if deterministic:
                by_key[key] = self._criterion_evaluation(
                    crit, deterministic, manual, workbook, validator)
                if manual:
                    manual_review_keys.append(key)
            else:
                by_key[key] = self._unverified_criterion(
                    crit, manual, workbook, validator)
                if manual:
                    manual_review_keys.append(key)

        # Written/documentation criteria are the only ones allowed a bounded
        # shared-AAGE model call: workbook mechanics stay deterministic.
        llm_keys = [
            str(c.get("criterion_key") or c.get("key") or "")
            for c in criteria
            if c not in (None, {}) and self._criterion_bucket(c) == "documentation"
            and not mapping.get(str(c.get("criterion_key") or c.get("key") or ""))
        ]
        if llm_keys and (ctx.manifest.text_content or "").strip():
            llm_criteria = [c for c in criteria
                            if str(c.get("criterion_key") or c.get("key") or "") in llm_keys]
            raw, call = self.run_llm(
                ctx, llm_criteria,
                extra_instructions=(
                    "- Grade written/documentation evidence only. Statements about "
                    "workbook results are student claims (CONTENT_SUPPORTED), never "
                    "VERIFIED.\n"
                    "- Do not contradict deterministic workbook analyzer findings."
                ))
            if raw:
                for ev in self._to_evaluations(llm_criteria, raw, ctx, call):
                    by_key[ev.criterion_key] = ev
                output.used_llm = True
                output.provider = getattr(call, "provider", None)
                output.latency_ms = getattr(call, "latency_ms", 0)
                output.overall_feedback = str(raw.get("overall_feedback") or "")[:4000]
                output.strengths = [str(s)[:300] for s in (raw.get("strengths") or [])][:10]
                output.improvements = [str(s)[:300] for s in (raw.get("improvements") or [])][:10]
            else:
                output.warnings.append(
                    "documentation criteria left unverified: model review unavailable")

        output.criteria = [
            by_key[str(c.get("criterion_key") or c.get("key") or "")]
            for c in criteria
            if str(c.get("criterion_key") or c.get("key") or "") in by_key
        ]
        # Defensive: never silently drop a rubric criterion.
        for idx, crit in enumerate(criteria):
            key = str(crit.get("criterion_key") or crit.get("key") or f"criterion_{idx}")
            if key not in by_key:
                output.criteria.append(self._unverified_criterion(crit, [], workbook, validator))

        if not output.used_llm:
            output.confidence = self._aggregate_confidence(output.criteria)

        if manual_review_keys:
            output.warnings.append(
                f"{len(manual_review_keys)} criterion/criteria depend on written "
                "evidence that requires instructor review")
        for req_id in req_eval.get("critical_failures") or []:
            output.warnings.append(f"critical requirement not satisfied: {req_id}")
        if req_eval.get("manual_review_required"):
            output.warnings.append("assessment contract flagged manual review")

        if not output.overall_feedback:
            output.overall_feedback = self._overall_feedback(req_results, output.criteria)
        if not output.strengths:
            output.strengths = self._narrative_lines(req_results, "SATISFIED")
        if not output.improvements:
            output.improvements = self._narrative_lines(
                req_results, "FAILED", alt_status="NOT_FOUND", limit=8)

        wb_analysis = analyses.get("workbook") or {}
        output.analysis = {
            "evaluator": self.name,
            "version": self.version,
            "workbook": {
                "path": workbook.path,
                "name": workbook.name,
                "sha256": workbook.sha256,
                "sheet_names": list(wb_analysis.get("sheet_names") or [])[:50],
                "error": str(wb_analysis.get("error") or "")[:400],
            },
            "spec": {
                "schema_version": spec.get("schema_version"),
                "engine_version": spec.get("engine_version"),
                "source_hash": spec.get("source_hash"),
                "requirement_count": len(spec.get("requirements") or []),
            },
            "analyzers": sorted(analyses.keys()),
            "requirement_summary": {
                "status_counts": req_eval.get("status_counts") or {},
                "critical_failures": req_eval.get("critical_failures") or [],
                "manual_review_required": bool(req_eval.get("manual_review_required")),
            },
            "criterion_mapping": mapping,
            "workbook_feature_observations": len(workbook_observations),
            "limitation": _INSPECTION_LIMITATION,
        }
        return output

    # ------------------------------------------------------------------
    # Deterministic analysis helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _workbooks(ctx: EvaluationContext) -> List[Any]:
        candidates = [f for f in ctx.artifact_files
                      if f.path.lower().endswith(EXCEL_EXT) and f.data]
        # Prefer real workbooks over an incidental CSV in the same submission.
        candidates.sort(key=lambda f: 0 if f.path.lower().endswith(WORKBOOK_EXT) else 1)
        return candidates

    @staticmethod
    def _build_spec(ctx: EvaluationContext) -> Dict[str, Any]:
        from ...excel_grading.assignment_intelligence import build_assignment_knowledge

        d = ctx.descriptor
        context = {
            "assignment_id": (d.id if d.kind == "assignment" else f"project:{d.id}"),
            "title": d.title,
            "description": d.description,
            "instructions": d.instructions,
            "course_id": d.course_id,
            "course_title": d.course_title,
            "module_id": d.module_id,
            "points_possible": d.points_possible,
        }
        try:
            return build_assignment_knowledge(context)
        except Exception:  # pragma: no cover - defensive for hostile briefs
            logger.exception("AAGE spreadsheet spec generation failed")
            return {
                "schema_version": "1.0", "engine_version": "2.0.0",
                "source_hash": "", "requirements": [], "rubric": {}, "scope": {},
            }

    @staticmethod
    def _run_analyzers(workbook: Any,
                       spec: Dict[str, Any]) -> Tuple[Dict[str, Dict[str, Any]], List[str]]:
        """Run pure analyzers; each failure degrades to an empty observation."""
        from ...excel_grading.chart_analyzer import ChartAnalyzer
        from ...excel_grading.dax_analyzer import DAXAnalyzer
        from ...excel_grading.excel_analyzer import ExcelAnalyzer
        from ...excel_grading.formatting_analyzer import FormattingAnalyzer
        from ...excel_grading.formula_analyzer import FormulaAnalyzer
        from ...excel_grading.pivot_analyzer import PivotAnalyzer
        from ...excel_grading.power_query_analyzer import PowerQueryAnalyzer
        from ...excel_grading.vba_analyzer import VBAAnalyzer

        analyses: Dict[str, Dict[str, Any]] = {"spec": spec}
        warnings: List[str] = []
        data = bytes(workbook.data)
        name = workbook.name or workbook.path

        try:
            analyses["workbook"] = ExcelAnalyzer(data, name).analyze()
        except Exception as exc:  # noqa: BLE001 - untrusted workbook
            warnings.append(f"workbook analysis failed: {str(exc)[:160]}")
            analyses["workbook"] = {"error": str(exc)[:400], "sheets": []}

        wb = analyses["workbook"]
        if wb.get("error"):
            warnings.append(f"workbook could not be inspected: {str(wb['error'])[:160]}")
            return analyses, warnings

        steps = (
            ("formulas", FormulaAnalyzer, (wb,)),
            ("charts", ChartAnalyzer, (wb,)),
            ("pivots", PivotAnalyzer, (data, wb)),
            ("vba", VBAAnalyzer, (data, wb)),
            ("power_query", PowerQueryAnalyzer, (data, wb)),
            ("dax", DAXAnalyzer, (data, wb)),
            ("formatting", FormattingAnalyzer, (wb,)),
        )
        for key, cls, args in steps:
            try:
                result = cls(*args).analyze()
                analyses[key] = result if isinstance(result, dict) else {}
            except Exception as exc:  # noqa: BLE001 - one analyzer must not kill the run
                warnings.append(f"{key} analyzer failed: {str(exc)[:160]}")
                analyses[key] = {}

        vba = analyses.get("vba") or {}
        security = vba.get("security") or {}
        if str(security.get("risk_level") or "").lower() in ("high", "critical"):
            warnings.append("VBA analyzer reported high-risk macro patterns")
        if wb.get("scan_truncated") or any(
                s.get("scan_truncated") for s in (wb.get("sheets") or [])
                if isinstance(s, dict)):
            warnings.append("workbook scan was truncated by safety limits")
        return analyses, warnings

    @staticmethod
    def _evaluate_requirements(spec: Dict[str, Any],
                               analyses: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
        from ...excel_grading.assignment_intelligence import RequirementEvaluator

        try:
            result = RequirementEvaluator().evaluate(spec, analyses)
            return result if isinstance(result, dict) else {}
        except Exception:  # pragma: no cover - defensive
            logger.exception("AAGE spreadsheet requirement evaluation failed")
            return {}

    # ------------------------------------------------------------------
    # Workbook feature observations for generic rubric criteria
    # ------------------------------------------------------------------

    @staticmethod
    def _observation(observation_id: str, requirement_type: str,
                     evidence: Sequence[str], *, fix: str,
                     confidence: float = 0.85) -> Dict[str, Any]:
        lines = [str(line).strip() for line in evidence if str(line).strip()]
        return {
            "requirement_id": observation_id,
            "requirement": observation_id.replace("feature_", "Workbook evidence: "),
            "type": requirement_type,
            "category": _REQ_CATEGORY_BUCKET.get(
                requirement_type.lower(), "Completeness"),
            "evidence_source": "workbook_structure",
            "max_score": 1.0,
            "score": 1.0 if lines else 0.0,
            "status": "SATISFIED" if lines else "NOT_FOUND",
            "confidence": confidence,
            "criticality": "normal",
            "method_constraint": "flexible",
            "evidence": lines,
            "missing": [] if lines else [fix],
            "fix": fix,
            "depends_on": [],
            "verification": {
                "type": "workbook_structure",
                "expected_functions": [],
                "target_cells": [],
                "required_sheets": [],
                "expected": {"static_workbook_feature": observation_id},
            },
        }

    @classmethod
    def _workbook_feature_observations(cls, spec: Dict[str, Any],
                                       analyses: Dict[str, Dict[str, Any]]
                                       ) -> List[Dict[str, Any]]:
        """Turn real analyzer facts into evidence for AAGE rubric buckets.

        These observations are deliberately additive: they cannot replace a
        failed assignment-specific requirement, and they are only emitted when
        the analyzer actually observed the feature.
        """
        observations: List[Dict[str, Any]] = []
        wb = analyses.get("workbook") or {}
        sheets = [s for s in (wb.get("sheets") or []) if isinstance(s, dict)]
        if wb.get("error") or not sheets:
            return observations

        values = [item for sheet in sheets for item in (sheet.get("values") or [])]
        formulas = [item for sheet in sheets for item in (sheet.get("formulas") or [])]
        charts = analyses.get("charts") or {}
        fmt = analyses.get("formatting") or {}
        pivots = analyses.get("pivots") or {}

        # Structure: named sheets, traceable headers and navigation/table aids.
        structure_lines: List[str] = []
        named = [s.get("name") for s in sheets if s.get("name")
                 and not str(s.get("name")).lower().startswith("sheet")]
        if named:
            structure_lines.append("Named worksheets detected: " + ", ".join(named[:6]))
        for sheet in sheets:
            text_cells = [i for i in (sheet.get("values") or [])
                          if isinstance(i.get("value"), str) and str(i.get("value")).strip()]
            if len(text_cells) >= 3:
                structure_lines.append(
                    f"Header/label row detected on '{sheet.get('name')}' with "
                    f"{len(text_cells)} text cells.")
                break
        aids = []
        if any(s.get("freeze_panes") for s in sheets):
            aids.append("frozen panes")
        if any(s.get("tables") for s in sheets):
            aids.append("structured tables")
        if any(s.get("auto_filter") for s in sheets):
            aids.append("AutoFilter")
        if aids:
            structure_lines.append("Workbook navigation aids detected: " + ", ".join(aids))
        if structure_lines:
            observations.append(cls._observation(
                "feature_structure", "STRUCTURE_REQUIREMENT", structure_lines,
                fix="Provide named worksheets, traceable headers and navigable data ranges."))

        # Visualisation: real chart objects and observed cell formatting.
        visual_lines: List[str] = []
        if charts.get("chart_count", 0):
            visual_lines.append(
                f"{charts.get('chart_count')} chart object(s) detected: "
                + ", ".join((charts.get("chart_types") or [])[:5]))
        style_signals = []
        for key, label in (("bold_cells", "bold cells"),
                           ("centered_cells", "centered cells"),
                           ("filled_cells", "filled cells"),
                           ("bottom_border_cells", "bordered cells"),
                           ("date_cells", "date-formatted cells"),
                           ("currency_cells", "currency-formatted cells"),
                           ("percentage_cells", "percentage-formatted cells")):
            count = sum(len(s.get(key) or []) for s in sheets)
            if count:
                style_signals.append(f"{count} {label}")
        if style_signals:
            visual_lines.append("Formatting evidence detected: " + ", ".join(style_signals))
        if visual_lines:
            observations.append(cls._observation(
                "feature_visualisation", "FORMAT_REQUIREMENT", visual_lines,
                fix="Add a readable chart and consistent header/data formatting."))

        # Validation: deterministic data-validation and conditional rules.
        validation_lines: List[str] = []
        validation_count = sum(len(s.get("data_validations") or []) for s in sheets)
        if validation_count or fmt.get("has_data_validation"):
            validation_lines.append(
                f"Data Validation rules detected in {validation_count} worksheet range(s).")
        cf_count = int(fmt.get("total_conditional_formatting_rules") or 0)
        if cf_count:
            validation_lines.append(f"Conditional formatting rules detected: {cf_count}.")
        if validation_lines:
            observations.append(cls._observation(
                "feature_validation", "DATA_VALIDATION_REQUIREMENT", validation_lines,
                fix="Add input validation or conditional rules where the brief requires them.",
                confidence=0.9))

        # Pivots/summaries: the criterion text allows a pivot table OR a
        # formula-driven summary.  Never claim a pivot cache that is absent.
        summary_lines: List[str] = []
        if pivots.get("pivot_count", 0):
            summary_lines.append(f"{pivots.get('pivot_count')} PivotTable(s) detected.")
        aggregate_functions = {"SUMIF", "SUMIFS", "SUM", "AVERAGE", "COUNT", "COUNTA"}
        for sheet in sheets:
            name = str(sheet.get("name") or "")
            if not any(word in name.lower() for word in ("summary", "report", "analysis")):
                continue
            aggregate = []
            for entry in (sheet.get("formulas") or []):
                text = str(entry.get("formula", "")).upper()
                if any(func + "(" in text for func in aggregate_functions):
                    aggregate.append(str(entry.get("cell")))
            if aggregate:
                summary_lines.append(
                    f"Formula-driven summary sheet '{name}' detected with "
                    f"{len(aggregate)} aggregate formula(s) at "
                    + ", ".join(aggregate[:6]) + ".")
        if summary_lines and not pivots.get("pivot_count"):
            summary_lines.append("No PivotTable cache was found; evidence is summary-formula based only.")
        if summary_lines:
            observations.append(cls._observation(
                "feature_pivots", "PIVOT_REQUIREMENT", summary_lines,
                fix="Provide a PivotTable or a formula-driven summary answering the brief.",
                confidence=0.82))

        # Documentation: only an in-workbook documentation sheet qualifies as
        # deterministic evidence for this workbook-specific evaluator.
        doc_lines: List[str] = []
        for sheet in sheets:
            name = str(sheet.get("name") or "").lower()
            if not any(word in name for word in ("documentation", "readme", "notes", "instructions")):
                continue
            text_items = [i for i in (sheet.get("values") or [])
                          if isinstance(i.get("value"), str) and len(str(i.get("value")).strip()) >= 8]
            if len(text_items) >= 3:
                doc_lines.append(
                    f"In-workbook documentation sheet '{sheet.get('name')}' contains "
                    f"{len(text_items)} explanatory text cell(s).")
                break
        if doc_lines:
            observations.append(cls._observation(
                "feature_documentation", "DOCUMENTATION_REQUIREMENT", doc_lines,
                fix="Document assumptions and steps inside the workbook."))

        # Namespaced OOXML/OPC observations.  Only PRESENT/CONFIGURED package
        # markers become evidence; ABSENT and UNVERIFIABLE records are skipped
        # so a clean scan cannot manufacture a failure and an unreadable
        # package cannot manufacture a pass.
        ooxml = (wb.get("ooxml_features") or {})
        if str((ooxml.get("scan") or {}).get("status") or "") == "scanned":
            ooxml_records = ooxml.get("features") or {}
            for key, (_bucket, requirement_type, label) in _OOXML_OBSERVATIONS.items():
                record = ooxml_records.get(key)
                if not isinstance(record, dict):
                    continue
                feature_status = str(record.get("status") or "").upper()
                if feature_status not in {"PRESENT", "CONFIGURED"}:
                    continue
                lines = [
                    f"{label}: {line}" for line in (record.get("evidence") or [])
                    if str(line).strip()
                ][:3]
                if not lines:
                    lines = [f"{label} package marker detected ({feature_status.lower()})."]
                observations.append(cls._observation(
                    f"feature_ooxml_{key}", requirement_type, lines,
                    fix=f"Retain the required {label.lower()} evidence in the workbook.",
                    confidence=0.86 if feature_status == "CONFIGURED" else 0.84,
                ))

        # Automation: only when the brief did not request VBA/Power Query.
        # Replace a false "macro missing" failure with evidence of the
        # spreadsheet automation the brief actually asked for.
        requirement_types = {str(r.get("type") or "") for r in
                             (spec.get("requirements") or []) if isinstance(r, dict)}
        advanced_types = {"VBA_REQUIREMENT", "CODE_STRUCTURE_REQUIREMENT",
                          "BUSINESS_LOGIC_REQUIREMENT", "WORKBOOK_BEHAVIOR_REQUIREMENT",
                          "POWER_QUERY_REQUIREMENT", "DAX_REQUIREMENT"}
        # The brief decides whether macros/queries are required.  An incidental
        # VBA archive in the workbook is not an assignment requirement and must
        # not suppress evidence for the spreadsheet automation that was asked
        # for (filled formulas, absolute references, tables/AutoFilter).
        macros_requested = bool(requirement_types & advanced_types)
        if not macros_requested:
            automation_lines: List[str] = []
            repeated = [f for f in formulas if re.search(r"\d", str(f.get("formula", "")))]
            normalized = {}
            for entry in repeated:
                key = (entry.get("sheet"),
                       re.sub(r"\d+", "#", str(entry.get("formula", ""))))
                normalized[key] = normalized.get(key, 0) + 1
            if any(count >= 3 for count in normalized.values()):
                automation_lines.append(
                    "Filled relative formula pattern detected across at least three cells.")
            if any(re.search(r"\$[A-Z]+\$?\d+|\$?[A-Z]+\$\d+",
                             str(f.get("formula", "")), re.I) for f in formulas):
                automation_lines.append("Absolute-reference formula detected.")
            if any(s.get("tables") or s.get("auto_filter") for s in sheets):
                automation_lines.append("Structured table/AutoFilter evidence detected.")
            if automation_lines:
                automation_lines.append(
                    "No VBA/Power Query requirement was present in the assignment brief; "
                    "this criterion was assessed on the workbook automation actually requested.")
                observations.append(cls._observation(
                    "feature_automation", "WORKBOOK_BEHAVIOR_REQUIREMENT",
                    automation_lines,
                    fix="Add the requested spreadsheet automation (filled formulas, "
                        "absolute references, tables or macros/queries when required).",
                    confidence=0.78))
        return observations

    # ------------------------------------------------------------------
    # Requirement <-> rubric mapping
    # ------------------------------------------------------------------

    @staticmethod
    def _tokens(text: Any) -> set:
        return {t for t in re.split(r"[^a-z0-9]+", str(text or "").lower()) if t}

    @classmethod
    def _criterion_bucket(cls, crit: Dict[str, Any]) -> str:
        tokens = cls._tokens(" ".join(str(crit.get(k) or "") for k in (
            "criterion_key", "key", "name", "description", "evaluator_hint")))
        # Specific criterion families win over generic layout words.  A
        # "Workbook structure" description may mention "layout", but that must
        # not route it to "Charts & formatting".
        for bucket in ("validation", "automation", "pivots", "documentation",
                       "formulas", "structure", "visualisation"):
            if tokens & _CRITERION_TOKENS.get(bucket, set()):
                return bucket
        return ""

    @classmethod
    def _requirement_bucket(cls, req: Dict[str, Any]) -> str:
        if str(req.get("type") or "") == "OOXML_FEATURE_REQUIREMENT":
            label = str(
                ((req.get("verification") or {}).get("expected") or {}).get("feature") or ""
            ).strip().lower()
            if label in _OOXML_FEATURE_BUCKET:
                return _OOXML_FEATURE_BUCKET[label]
        bucket = _REQ_TYPE_BUCKET.get(str(req.get("type") or ""))
        if bucket:
            return bucket
        category = str(req.get("category") or "").strip().lower()
        if category in _REQ_CATEGORY_BUCKET:
            return _REQ_CATEGORY_BUCKET[category]
        source = str(req.get("evidence_source") or "")
        return {
            "formula": "formulas", "cell_value": "structure",
            "worksheet": "structure", "workbook_structure": "structure",
            "chart": "visualisation", "pivot": "pivots",
            "vba_code": "automation", "m_code": "automation",
            "dax_measure": "formulas", "written_evidence": "documentation",
        }.get(source, "structure")

    @classmethod
    def _match_requirements(cls, crit: Dict[str, Any],
                            reqs: Sequence[Dict[str, Any]]
                            ) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
        """Return (deterministic observations, manual-review observations)."""
        key = str(crit.get("criterion_key") or crit.get("key") or "")
        explicit_ids = {key, str(crit.get("id") or "")} - {""}
        direct = [r for r in reqs if str(r.get("requirement_id") or "") in explicit_ids]
        if direct:
            matched = direct
        else:
            bucket = cls._criterion_bucket(crit)
            bucket_matches = [r for r in reqs if cls._requirement_bucket(r) == bucket] if bucket else []
            if bucket_matches:
                matched = bucket_matches
            else:
                crit_tokens = cls._tokens(" ".join(str(crit.get(k) or "") for k in
                                                   ("criterion_key", "key", "name",
                                                    "description")))
                matched = [
                    r for r in reqs
                    if len(crit_tokens & cls._tokens(r.get("requirement"))) >= 2
                ]
        deterministic = [r for r in matched
                         if r.get("status") != "MANUAL_REVIEW"]
        manual = [r for r in matched if r.get("status") == "MANUAL_REVIEW"]
        return deterministic, manual

    # ------------------------------------------------------------------
    # Criterion construction
    # ------------------------------------------------------------------

    @classmethod
    def _criterion_evaluation(cls, crit: Dict[str, Any],
                              reqs: Sequence[Dict[str, Any]],
                              manual: Sequence[Dict[str, Any]],
                              workbook: Any,
                              validator: EvidenceValidator) -> CriterionEvaluation:
        key = str(crit.get("criterion_key") or crit.get("key") or "")
        maximum = float(crit.get("max_marks") or 0)
        ratios = [_STATUS_RATIO.get(str(r.get("status")), 0.0) for r in reqs]
        ratios = [float(r) for r in ratios if r is not None]
        ratio = sum(ratios) / len(ratios) if ratios else 0.0
        marks = round(max(0.0, min(maximum, ratio * maximum)), 4)

        statuses = [str(r.get("status")) for r in reqs]
        confirmed = any(s in ("SATISFIED", "EXCEEDED", "PARTIAL", "FAILED") for s in statuses)
        all_satisfied = bool(statuses) and all(s in ("SATISFIED", "EXCEEDED") for s in statuses)
        any_manual = bool(manual) or "MANUAL_REVIEW" in statuses

        raw_evidence: List[Dict[str, Any]] = []
        for req in list(reqs) + list(manual):
            rid = str(req.get("requirement_id") or "")
            status = str(req.get("status") or "NOT_FOUND")
            category = ("VERIFIED" if status in ("SATISFIED", "EXCEEDED") else
                        ("CODE_SUPPORTED" if status in ("PARTIAL", "FAILED") else
                         "UNVERIFIED"))
            evidence_lines = [str(x) for x in (req.get("evidence") or []) if str(x).strip()]
            missing_lines = [str(x) for x in (req.get("missing") or []) if str(x).strip()]
            locator = cls._locator(req)
            for line in evidence_lines[:3]:
                raw_evidence.append({
                    "category": category,
                    "source": "analyzer",
                    "reference": workbook.path,
                    "locator": locator,
                    "summary": line[:600],
                    "detail": {
                        "requirement_id": rid,
                        "status": status,
                        "evidence_source": req.get("evidence_source"),
                        "type": req.get("type"),
                    },
                    "confidence": 0.9 if category == "VERIFIED" else 0.75,
                })
            for line in missing_lines[:2]:
                raw_evidence.append({
                    "category": "UNVERIFIED",
                    "source": "analyzer",
                    "reference": workbook.path,
                    "locator": locator,
                    "summary": line[:600],
                    "detail": {"requirement_id": rid, "status": status, "kind": "missing"},
                    "confidence": 0.35,
                })
        evidence = validator.validate(raw_evidence, criterion_key=key)
        if not any(e.get("category") == "UNVERIFIED" for e in evidence):
            category = "VERIFIED" if all_satisfied else "CODE_SUPPORTED"
            verification = "verified" if all_satisfied else "partial"
        else:
            category = "CODE_SUPPORTED" if confirmed else "UNVERIFIED"
            verification = "partial" if confirmed else "unverified"

        rationale_parts = [
            f"{len(reqs)} deterministic spreadsheet requirement observation(s) mapped "
            f"to this criterion; {sum(1 for s in statuses if s == 'SATISFIED')} satisfied, "
            f"{sum(1 for s in statuses if s == 'PARTIAL')} partial, "
            f"{sum(1 for s in statuses if s in ('FAILED', 'NOT_FOUND'))} not met."
        ]
        for req in reqs[:4]:
            evidence_line = next((str(x) for x in (req.get("evidence") or []) if str(x).strip()), "")
            rationale_parts.append(
                f"{req.get('requirement_id')} ({req.get('status')}): {evidence_line[:220]}")
        rationale = " ".join(rationale_parts)[:2000]

        feedback: List[str] = []
        for req in reqs + list(manual):
            if str(req.get("status")) in ("SATISFIED", "EXCEEDED", "NOT_APPLICABLE"):
                continue
            fix = str(req.get("fix") or "").strip()
            if fix:
                feedback.append(fix)
            for miss in (req.get("missing") or [])[:2]:
                text = str(miss).strip()
                if text:
                    feedback.append(text)
        feedback_text = " ".join(dict.fromkeys(feedback))[:1200]

        confidence = 0.9 if all_satisfied and confirmed else (
            0.7 if confirmed and not any(s in ("FAILED", "NOT_FOUND") for s in statuses) else
            0.6 if confirmed else 0.35 if any_manual else 0.0)

        limitations = _INSPECTION_LIMITATION
        if any_manual:
            limitations += " Written/deliverable observations require instructor review."

        return CriterionEvaluation(
            criterion_key=key,
            marks=marks,
            max_marks=maximum,
            rationale=rationale,
            evidence_category=category,
            verification_status=verification,
            evidence=evidence,
            feedback=feedback_text,
            limitations=limitations[:900],
            confidence=confidence,
            evaluator_name=cls.name,
            evaluator_version=cls.version,
        )

    @classmethod
    def _unverified_criterion(cls, crit: Dict[str, Any],
                              manual: Sequence[Dict[str, Any]],
                              workbook: Any,
                              validator: EvidenceValidator) -> CriterionEvaluation:
        key = str(crit.get("criterion_key") or crit.get("key") or "")
        max_marks = float(crit.get("max_marks") or 0)
        if manual:
            raw = [{
                "category": "UNVERIFIED", "source": "analyzer",
                "reference": workbook.path, "locator": cls._locator(manual[0]),
                "summary": "Written/deliverable requirement requires instructor review: "
                           + str(manual[0].get("requirement") or "")[:300],
                "confidence": 0.3,
            }]
            evidence = validator.validate(raw, criterion_key=key)
            rationale = ("No deterministic workbook observation maps to this criterion; "
                         "the linked requirement needs instructor review.")
            confidence = 0.35
        else:
            evidence = []
            rationale = "No deterministic spreadsheet evidence maps to this criterion."
            confidence = 0.0
        return CriterionEvaluation(
            criterion_key=key, marks=0.0, max_marks=max_marks,
            rationale=rationale, evidence_category="UNVERIFIED",
            verification_status="unverified", evidence=evidence,
            feedback=("Provide the written evidence requested for this criterion."
                      if manual else "Address this criterion in the submitted workbook."),
            limitations=_INSPECTION_LIMITATION,
            confidence=confidence,
            evaluator_name=cls.name, evaluator_version=cls.version,
        )

    @staticmethod
    def _locator(req: Dict[str, Any]) -> str:
        verification = req.get("verification") or {}
        cells = verification.get("target_cells") or []
        if isinstance(cells, list) and cells:
            first = cells[0] if isinstance(cells[0], dict) else {}
            sheet = str(first.get("sheet") or "")
            cell = str(first.get("cell") or "")
            if sheet and cell:
                return f"{sheet}!{cell}"
            if cell:
                return cell
        sheets = verification.get("required_sheets") or []
        if isinstance(sheets, list) and sheets:
            return str(sheets[0])
        return str(req.get("requirement_id") or "")

    @staticmethod
    def _unverified_criteria(criteria: Sequence[Dict[str, Any]],
                             reason: str) -> List[CriterionEvaluation]:
        return [
            CriterionEvaluation(
                criterion_key=str(c.get("criterion_key") or c.get("key") or ""),
                marks=0.0, max_marks=float(c.get("max_marks") or 0),
                rationale=f"spreadsheet analysis could not run ({reason})",
                evidence_category="UNVERIFIED", verification_status="unverified",
                feedback="Submit an accessible workbook so deterministic analysis can run.",
                limitations=_INSPECTION_LIMITATION,
                evaluator_name="spreadsheet", evaluator_version="2.0.0",
                confidence=0.0,
            )
            for c in criteria
        ]

    @staticmethod
    def _aggregate_confidence(criteria: Sequence[CriterionEvaluation]) -> float:
        total_weight = sum(max(0.0, c.max_marks) for c in criteria)
        if total_weight <= 0:
            return 0.0
        value = sum(max(0.0, c.confidence) * max(0.0, c.max_marks)
                    for c in criteria) / total_weight
        return round(max(0.0, min(1.0, value)), 3)

    @staticmethod
    def _overall_feedback(reqs: Sequence[Dict[str, Any]],
                          criteria: Sequence[CriterionEvaluation]) -> str:
        unmet = [r for r in reqs if r.get("status") in ("FAILED", "NOT_FOUND", "PARTIAL")]
        if unmet:
            parts = [f"{r.get('requirement_id')}: {r.get('fix') or r.get('requirement')}"
                     for r in unmet[:5]]
            return ("Deterministic workbook inspection identified gaps. " + " ".join(parts))[:4000]
        if criteria and all(c.verification_status == "verified" for c in criteria):
            return ("Deterministic workbook inspection confirmed the mapped spreadsheet "
                    "requirements. " + _INSPECTION_LIMITATION)[:4000]
        return ("Spreadsheet analysis completed; see criterion evidence for details. "
                + _INSPECTION_LIMITATION)[:4000]

    @staticmethod
    def _narrative_lines(reqs: Sequence[Dict[str, Any]], status: str, *,
                         alt_status: Optional[str] = None,
                         limit: int = 5) -> List[str]:
        lines: List[str] = []
        for req in reqs:
            if req.get("status") == status or (alt_status and req.get("status") == alt_status):
                text = str(req.get("requirement") or req.get("requirement_id") or "").strip()
                if text:
                    lines.append(text[:300])
            if len(lines) >= limit:
                break
        return lines


