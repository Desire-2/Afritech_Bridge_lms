def normalize_language(lang):
    value = str(lang or 'en').lower()
    return value if value in SUPPORTED_LANGUAGES else 'en'


def bilingual(key, **kwargs):
    """Return both official languages in one message when no user locale exists."""
    return ' / '.join((t(key, 'en', **kwargs), t(key, 'rw', **kwargs)))


def t(key, lang='en', **kwargs):
    value = LABELS.get(normalize_language(lang), LABELS['en']).get(key)
    if value is None:
        value = LABELS['en'].get(key, key)
    try:
        return value.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return value
