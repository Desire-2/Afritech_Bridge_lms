const dictionaries: Record<TalentPassportLanguage, Dictionary> = { en, fr, rw };

export function normalizeTalentPassportLanguage(value?: string | null): TalentPassportLanguage {
  const normalized = (value || '').toLowerCase();
  if (normalized.startsWith('fr')) return 'fr';
  if (normalized.startsWith('rw')) return 'rw';
  if (normalized.startsWith('en')) return 'en';
  return 'en';
}

export function resolveTalentPassportDictionary(language?: string | null): Dictionary {
  return dictionaries[normalizeTalentPassportLanguage(language)];
}

/** Hook used by every passport component for user-facing copy. */
export function useTalentPassportI18n(language?: string) {
  const [detected, setDetected] = useState<TalentPassportLanguage>('en');

  useEffect(() => {
    if (language) {
      setDetected(normalizeTalentPassportLanguage(language));
      return;
    }
    if (typeof window === 'undefined') return;
    try {
      const stored = window.localStorage.getItem('language');
      const browser = window.navigator.language;
      setDetected(normalizeTalentPassportLanguage(stored || browser));
    } catch {
      setDetected('en');
    }
  }, [language]);

  const active: TalentPassportLanguage = language
    ? normalizeTalentPassportLanguage(language)
    : detected;
  const dictionary = dictionaries[active];

  const t = (key: TalentPassportTranslationKey, values?: Record<string, string | number>): string => {
    const template = dictionary[key] ?? en[key];
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
    );
  };

  return { language: active, t, dictionary };
}
